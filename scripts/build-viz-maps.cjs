// Regenerate the bundled map backgrounds with Node 18+; no build needed to run the app.
// Natural Earth 1:110m, public domain: https://www.naturalearthdata.com/about/terms-of-use/
const fs = require("node:fs/promises");
const path = require("node:path");
const vm = require("node:vm");

async function main() {
  const root = path.resolve(__dirname, "..");
  const context = vm.createContext({});
  vm.runInContext(await fs.readFile(path.join(root, "viz.js"), "utf8"), context);
  const regions = vm.runInContext("VIZ_REGIONS", context);
  const project = vm.runInContext("vizProject", context);
  const base = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/";
  const [land, states] = await Promise.all(["ne_110m_admin_0_countries", "ne_110m_admin_1_states_provinces_lines"].map(async (name) => {
    const response = await fetch(`${base}${name}.geojson`);
    if (!response.ok) throw new Error(`Map download failed: ${response.status}`);
    return response.json();
  }));
  const folder = path.join(root, "img", "maps");
  await fs.mkdir(folder, { recursive: true });
  for (const [key, region] of Object.entries(regions)) {
    const [west, east, south, north] = region.bounds;
    const point = ([lon, lat]) => project(lon, lat, region.bounds).map((n) => Number(n.toFixed(1))).join(",");
    const intersects = (ring) => {
      const lon = ring.map((p) => p[0]);
      const lat = ring.map((p) => p[1]);
      return Math.max(...lon) >= west && Math.min(...lon) <= east && Math.max(...lat) >= south && Math.min(...lat) <= north;
    };
    const rings = land.features.flatMap((feature) => feature.geometry.type === "Polygon" ? feature.geometry.coordinates : feature.geometry.coordinates.flat());
    const outlines = rings.filter(intersects).map((ring) => `<path d="M${ring.map(point).join("L")}Z"/>`).join("");
    const lines = states.features.flatMap((feature) => feature.geometry.type === "LineString" ? [feature.geometry.coordinates] : feature.geometry.coordinates);
    const stateLines = key === "us" ? lines.filter(intersects).map((line) => `<path d="M${line.map(point).join("L")}"/>`).join("") : "";
    const graticule = [];
    for (let lon = Math.ceil(west / 10) * 10; lon < east; lon += 10) graticule.push(`<path d="M${point([lon, south])}L${point([lon, north])}"/>`);
    for (let lat = Math.ceil(south / 10) * 10; lat < north; lat += 10) graticule.push(`<path d="M${point([west, lat])}L${point([east, lat])}"/>`);
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 800 380"><!-- Natural Earth 1:110m, public domain. Generated by scripts/build-viz-maps.cjs. --><rect width="800" height="380" fill="#eaf0ed"/><g fill="none" stroke="#dce6df" stroke-width="0.6">${graticule.join("")}</g><g fill="#f5f4e9" stroke="#c7d2c0" stroke-width="1" stroke-linejoin="round">${outlines}</g><g fill="none" stroke="#d4dacb" stroke-width="0.8">${stateLines}</g></svg>\n`;
    await fs.writeFile(path.join(folder, `${key}.svg`), svg);
    console.log(`${key}.svg: ${Math.round(svg.length / 1024)} KB`);
  }
}
main().catch((error) => { console.error(error); process.exitCode = 1; });
