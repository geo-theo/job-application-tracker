// Regenerate the bundled map backgrounds with Node 18+; no build needed to run the app.
// Natural Earth 1:110m, public domain: https://www.naturalearthdata.com/about/terms-of-use/
const fs = require("node:fs/promises");
const path = require("node:path");

async function main() {
  const root = path.resolve(__dirname, "..");
  const base = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/";
  const [land, states] = await Promise.all(["ne_110m_admin_0_countries", "ne_110m_admin_1_states_provinces_lines"].map(async (name) => {
    const response = await fetch(`${base}${name}.geojson`);
    if (!response.ok) throw new Error(`Map download failed: ${response.status}`);
    return response.json();
  }));
  const area = (ring) => Math.abs(ring.reduce((sum, point, index) => {
    const next = ring[(index + 1) % ring.length];
    return sum + point[0] * next[1] - next[0] * point[1];
  }, 0));
  const countries = {};
  const outlines = [];
  land.features.forEach((feature) => {
    const props = feature.properties;
    const key = (props.ISO_A2_EH !== "-99" ? props.ISO_A2_EH : props.ADM0_A3).toLowerCase();
    const rings = (feature.geometry.type === "Polygon" ? feature.geometry.coordinates : feature.geometry.coordinates.flat())
      .map((ring) => ring.map((point) => point.map((n) => Number(n.toFixed(3)))));
    const mainland = rings.reduce((largest, ring) => area(ring) > area(largest) ? ring : largest, rings[0]);
    const lons = mainland.map((point) => point[0]);
    const lats = mainland.map((point) => point[1]);
    countries[key] = { label: props.NAME_EN || props.NAME, aliases: [...new Set([props.NAME, props.NAME_LONG, props.ADMIN, props.NAME_EN, props.ISO_A2_EH, props.ADM0_A3])].filter(Boolean),
      bounds: [Math.min(...lons), Math.max(...lons), Math.min(...lats), Math.max(...lats)] };
    outlines.push(...rings);
  });
  const lines = states.features.flatMap((feature) => feature.geometry.type === "LineString" ? [feature.geometry.coordinates] : feature.geometry.coordinates)
    .map((line) => line.map((point) => point.map((n) => Number(n.toFixed(3)))));
  const source = `// Generated by scripts/build-viz-maps.cjs. Natural Earth 1:110m, public domain.\n// https://www.naturalearthdata.com/about/terms-of-use/\nconst VIZ_COUNTRIES = ${JSON.stringify(countries)};\nconst VIZ_LAND = ${JSON.stringify(outlines)};\nconst VIZ_STATE_LINES = ${JSON.stringify(lines)};\n`;
  await fs.writeFile(path.join(root, "viz-geography.js"), source);
  console.log(`viz-geography.js: ${Object.keys(countries).length} countries, ${Math.round(source.length / 1024)} KB`);
}
main().catch((error) => { console.error(error); process.exitCode = 1; });
